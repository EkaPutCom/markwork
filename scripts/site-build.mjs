// Share the app's design tokens, fonts and Lucide icons with the static website. Run after changing the app theme.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { icons } from 'lucide';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'docs', 'web');
mkdirSync(join(out, 'fonts'), { recursive: true });
const source = readFileSync(join(root, 'electron/renderer/styles/globals.css'), 'utf8');
const light = source.match(/^:root \{[\s\S]*?^\}/m)?.[0];
const dark = source.match(/^:root\[data-theme="dark"\] \{[\s\S]*?^\}/m)?.[0];
if (!light || !dark) throw new Error('Could not find the app theme declarations.');
writeFileSync(join(out, 'tokens.css'), `/* Generated by npm run site:build from the application theme. Do not edit by hand. */\n${light}\n${dark}\n`);
for (const [family, target] of [['geist', 'geist'], ['geist-mono', 'mono']]) {
    const dir = join(root, 'node_modules', '@fontsource-variable', family);
    copyFileSync(join(dir, 'files', `${family}-latin-wght-normal.woff2`), join(out, 'fonts', `${target}.woff2`));
    copyFileSync(join(dir, 'LICENSE'), join(out, 'fonts', `${target}-LICENSE`));
}
const names = ['house', 'book-open', 'git-branch', 'arrow-up-right', 'folder-open', 'chevrons-up-down', 'file-text',
    'workflow', 'download', 'arrow-down', 'folder-heart', 'moon', 'sun', 'panel-left', 'chevron-right', 'check', 'mouse-pointer-2',
    'files', 'square-kanban', 'git-pull-request', 'terminal', 'laptop', 'monitor', 'folder', 'search', 'arrow-right', 'x'];
const escape = s => String(s).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
const glyphs = names.map(name => {
    const key = name.split('-').map(p => p[0].toUpperCase() + p.slice(1)).join('');
    const nodes = icons[key];
    if (!nodes) throw new Error(`Unknown Lucide icon: ${name}`);
    return [name, nodes.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([key, value]) => `${key}="${escape(value)}"`).join(' ')}/>`).join('')];
});
// A classic script and inline SVG work from file:// too; external SVG <use> requests do not.
writeFileSync(join(out, 'icons.js'), `// Generated from Lucide by npm run site:build.\nwindow.markworkIcons = Object.freeze(${JSON.stringify(Object.fromEntries(glyphs))});\n`);
copyFileSync(join(root, 'node_modules/lucide/LICENSE'), join(out, 'icons-LICENSE'));
console.log('Website tokens, fonts, and icons generated from the app design system.');
