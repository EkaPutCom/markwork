export type CoreFocus = 'all' | 'worktrees' | 'daemon' | 'agent-folders';

// Runs the tests one module after another; a module whose tests wait is awaited before the next starts.
export async function runCoreTests(focus: CoreFocus = 'all'): Promise<void> {
    if (focus === 'agent-folders') { await agentFolderTests(); return; }
    if (focus === 'worktrees') {
        harnessTests();
        await worktreeTests();
        return;
    }
    if (focus === 'daemon') {
        await daemonClientTests();
        await daemonAppTests();
        await programsTests();
        await daemonLiveTests();
        await daemonSshTests();
        return;
    }
    inlineTests();
    inlineHtmlTests();
    highlightTests();
    wikiLinkTests();
    searchTests();
    searchFilterTests();
    kanbanModelTests();
    inboxModelTests();
    fieldsModelTests();
    blurTests();
    layoutTests();
    tableTests();
    blockTests();
    paneTests();
    tableLayoutTests();
    clickTests();
    editCommandTests();
    layoutsModelTests();
    sampleDocumentTests();
    homeModelTests();
    journalModelTests();
    htmlTests();
    htmlViewTests();
    csvTests();
    pageTabTests();
    dbmlTests();
    gitLogTests();
    diffViewTests();
    await fileWriteTests();
    fileOpsTests();
    await filesControllerTests();
    await searchControllerTests();
    await outlineTests();
    await preferencesTests();
    await workspaceTests();
    await chatControllerTests();
    await agentFolderTests();
    await agentTests();
    await apiKeyTests();
    toolTests();
    transcriptTests();
    await workTests();
    await traceTests();
    await agenticTests();
    noteToolTests();
    await agentActionTests();
    await changeTests();
    await deepseekTests();
    await forgeTests();
    await platformTests();
    await appSessionTests();
    await protocolTests();
    await noteEditTests();
    await assistantTests();
    await historyControllerTests();
    await discardTests();
    appSettingsTests();
    noteDiffTests();
    await contributeTests();
    await publishTests();
    await resolveTests();
    conflictTests();
    await commitMessageTests();
    harnessTests();
    await worktreeTests();
    await daemonClientTests();
    await daemonAppTests();
    await programsTests();
    await daemonLiveTests();
    await daemonSshTests();
}
